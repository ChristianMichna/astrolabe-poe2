import { z } from "zod";
import { CatalogDiff, CatalogManifest, CatalogShard } from "./catalog/release.js";
import { CalcResult } from "./calc/result.js";
import { CalcMethods } from "./calc/rpc.js";
import { BuildRequest } from "./build/request.js";
import { CandidateComparisonView } from "./build/candidate-view.js";
import { GuideDocument } from "./guide/document.js";
import { GuideView } from "./guide/view.js";
import { PassiveTreeData, TreeIconAtlas } from "./guide/tree.js";
import { GuideCommentRequest, GuideCommentsView } from "./guide/comments.js";
import { GuideFile } from "./guide/file.js";
import { GuideListView } from "./guide/list.js";
import { GuidePatchStatusView, GuideTools, PatchStatus } from "./guide/patch-status.js";
import { ForgeTools } from "./forge/tools.js";
import { EconomyTools, PriceBook } from "./economy/price.js";
import { CraftTools } from "./craft/sim.js";
import { RunEvent } from "./events/run-events.js";

/**
 * Schemas published as JSON Schema files under schemas/ (generated by
 * `pnpm --filter @astrolabe/contracts generate`, checked by a snapshot test).
 * Consumers outside TypeScript (Lua worker tests, LLM tool definitions) use these.
 */
export const jsonSchemas: Readonly<Record<string, z.ZodType>> = {
  "catalog/manifest": CatalogManifest,
  "catalog/shard": CatalogShard,
  "catalog/diff": CatalogDiff,
  "calc/result": CalcResult,
  ...Object.fromEntries(
    Object.entries(CalcMethods).flatMap(([name, m]) => [
      [`calc/methods/${name}.params`, m.params],
      [`calc/methods/${name}.result`, m.result],
    ]),
  ),
  "build/request": BuildRequest,
  "build/candidate-view": CandidateComparisonView,
  "guide/document": GuideDocument,
  "guide/patch-status": PatchStatus,
  "guide/patch-status-view": GuidePatchStatusView,
  "guide/list": GuideListView,
  "guide/comment-request": GuideCommentRequest,
  "guide/comments-view": GuideCommentsView,
  "guide/view": GuideView,
  "guide/tree": PassiveTreeData,
  "guide/tree-icons": TreeIconAtlas,
  "guide/file": GuideFile,
  "events/run-event": RunEvent,
  "economy/price-book": PriceBook,
  ...Object.fromEntries(
    Object.entries(EconomyTools).flatMap(([name, t]) => [
      [`economy/${name}.input`, t.input],
      [`economy/${name}.output`, t.output],
    ]),
  ),
  ...Object.fromEntries(
    Object.entries(GuideTools).flatMap(([name, t]) => [
      [`guide/${name}.input`, t.input],
      [`guide/${name}.output`, t.output],
    ]),
  ),
  ...Object.fromEntries(
    Object.entries(CraftTools).flatMap(([name, t]) => [
      [`craft/${name}.input`, t.input],
      [`craft/${name}.output`, t.output],
    ]),
  ),
  ...Object.fromEntries(
    Object.entries(ForgeTools).flatMap(([name, t]) => [
      [`forge/${name}.input`, t.input],
      [`forge/${name}.output`, t.output],
    ]),
  ),
};

/**
 * Renders every published schema as formatted JSON, keyed by relative file
 * path. Input mode: describes what producers may write (defaults optional).
 */
export function renderJsonSchemas(): Record<string, string> {
  const files: Record<string, string> = {};
  for (const [name, schema] of Object.entries(jsonSchemas)) {
    const json = z.toJSONSchema(schema, { io: "input", target: "draft-2020-12" });
    files[`${name}.schema.json`] = `${JSON.stringify(json, null, 2)}\n`;
  }
  return files;
}
